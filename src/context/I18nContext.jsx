// Fallback resolver for minority languages (mai, sat, doi, sd, mni, brx, ks, kok) mapping to cognate Hindi translations
const COGNATE_FALLBACKS = {
  mai: 'hi',
  sat: 'hi',
  doi: 'hi',
  sd: 'hi',
  mni: 'bn',
  brx: 'as',
  ks: 'ur',
  kok: 'mr',
}

const I18nContext = createContext()

export function I18nProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    return localStorage.getItem('sahakar_lang') || 'mr'
  })

  useEffect(() => {
    localStorage.setItem('sahakar_lang', language)
  }, [language])

  const t = (key, fallback) => {
    // 1. Direct language dictionary lookup
    const langDict = translations[language]
    if (langDict && langDict[key]) {
      return langDict[key]
    }

    // 2. Cognate language fallback lookup (e.g. Kokani -> Marathi, Maithili -> Hindi, Bodo -> Assamese)
    const cognateCode = COGNATE_FALLBACKS[language]
    if (cognateCode && translations[cognateCode] && translations[cognateCode][key]) {
      return translations[cognateCode][key]
    }

    // 3. Hindi fallback
    if (translations.hi && translations.hi[key]) {
      return translations.hi[key]
    }

    // 4. English fallback
    if (translations.en && translations.en[key]) {
      return translations.en[key]
    }

    return fallback !== undefined ? fallback : key
  }

  const changeLanguage = (code) => {
    setLanguage(code)
  }

  return (
    <I18nContext.Provider value={{ language, setLanguage: changeLanguage, t, languages: INDIAN_LANGUAGES }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useTranslation() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useTranslation must be used within an I18nProvider')
  }
  return context
}
